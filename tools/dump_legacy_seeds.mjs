// Dumps legacy/index.html seed -> (patch, melody) results as the oracle for the Rust engine.
// The seeded path (mulberry32, withSeed, roll, rollLfo, makeStep, makeSeq, characterOf) is sliced
// out of the legacy source by text markers and run in a node:vm sandbox with minimal stubs
// (skin = amber, no carry, no audio context). legacy/ is never modified.
// Usage: node tools/dump_legacy_seeds.mjs [out.json]
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const src = fs.readFileSync(path.join(root, 'legacy/index.html'), 'utf8');

function slice(from, to) {
  const a = src.indexOf(from);
  if (a < 0) throw new Error('marker not found: ' + from);
  const b = src.indexOf(to, a);
  if (b < 0) throw new Error('marker not found: ' + to);
  return src.slice(a, b);
}

const code = [
  slice("const NOTES = [", "/* ---------- audio ---------- */"),   // constants, rnd/lrnd/pick, mulberry32, withSeed
  slice("function roll() {", "let cur = null;"),                   // roll + rollLfo
  slice("function makeStep(s) {", "function stepNote(s, t)"),      // makeStep, carry, makeSeq
  slice("function characterOf(sq, p) {", "function applyMood(ch)"),
].join('\n');

const SEEDS = [0, 1, 42, 16777217, 4294967295, 2166136261];

const harness = `
  const document = { documentElement: { getAttribute: () => 'amber', dataset: { skin: 'amber' } } };
  const root = document.documentElement;
  let tapPatch = null;
  const VOICES = {}, TW = {};
  function rollDub() { throw new Error('non-amber path reached'); }
  function ensureLfo(p) { return null; }   // WebAudio only; draws nothing
  ${code}
  const _mb = mulberry32;
  function dumpSeed(seed) {
    let n = 0;
    mulberry32 = a => { const g = _mb(a); return () => { n++; return g(); }; };
    let patch, seq, afterRoll;
    withSeed(seed, () => { patch = roll(); tapPatch = patch; afterRoll = n; seq = makeSeq(); });
    mulberry32 = _mb;
    const ch = characterOf(seq, patch);
    const g = _mb(seed), raw = [];
    for (let i = 0; i < 8; i++) raw.push(g());
    return {
      seed,
      rng_first8: raw,
      rng_first8_u32: raw.map(x => x * 4294967296),
      draws_after_roll: afterRoll,
      draws_total: n,
      patch,
      bpm: seq.bpm,
      root: seq.root,
      scale: seq.sc.name,
      scale_iv: seq.sc.iv,
      pool_len: seq.pool.length,
      start_idx: null,
      character: ch,
      steps: seq.steps.map(s => s && { note: s.midi, velocity: s.vel }),
    };
  }
`;

const ctx = vm.createContext({});
vm.runInContext(harness, ctx);
const out = {
  note: 'generated by tools/dump_legacy_seeds.mjs from legacy/index.html; skin=amber, no carry; steps[i] is null for a rest',
  seed_version: vm.runInContext('SEED_VERSION', ctx),
  seeds: SEEDS.map(s => vm.runInContext(`dumpSeed(${s})`, ctx)),
};
for (const e of out.seeds) {
  delete e.start_idx;
  if (e.steps.length !== 16) throw new Error('seed ' + e.seed + ': not 16 steps');
  if (!e.steps[0] || e.steps[0].velocity !== 1) throw new Error('seed ' + e.seed + ': step 0 velocity != 1');
}
const target = process.argv[2] || path.join(root, 'crates/engine/tests/fixtures/legacy_seeds.json');
fs.writeFileSync(target, JSON.stringify(out, null, 2) + '\n');
console.log('wrote', target);
